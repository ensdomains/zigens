#!/usr/bin/env python3
"""Transpile the canonical SQLite schema into a PostgreSQL schema.

`schema/schema.sql` (+ `schema/webhooks/*.sql`) is the single source of truth.
This tool mechanically derives `schema/postgres/…` so the two never drift, applying
the type-class rules from docs/postgresql-migration-plan.md:

  B1  every SQLite INTEGER -> PG BIGINT (incl. boolish columns; never emit BOOLEAN)
  B2  the lone BOOLEAN (v1_controllers.is_active) -> SMALLINT; DEFAULT TRUE/FALSE -> 1/0
  B3  TEXT stays TEXT (u256/hash/addr columns)
  B4  json_extract(col,'$.k') in DDL -> (col::jsonb ->> 'k')
  +   INTEGER PRIMARY KEY AUTOINCREMENT -> BIGSERIAL PRIMARY KEY
  +   strftime('%s','now') -> EXTRACT(EPOCH FROM now())::bigint
  +   INSERT OR IGNORE (seed rows) -> INSERT ... ON CONFLICT DO NOTHING

A guard fails the build if any unhandled SQLite-ism survives the transform, so a
new DDL construct can't silently produce invalid Postgres DDL. Run on `zig build`.
"""

import re
import sys
import pathlib

HEADER = (
    "-- GENERATED by tools/gen_pg_schema.py from {src} — DO NOT EDIT.\n"
    "-- Edit the canonical SQLite schema instead; this is the transpiled Postgres form.\n\n"
)

# Tokens that must NOT survive the transform (else: unhandled construct -> fail).
FORBIDDEN = [
    (r"\bAUTOINCREMENT\b", "AUTOINCREMENT"),
    (r"\bINTEGER\b", "INTEGER (should be BIGINT/BIGSERIAL)"),
    (r"\bBOOLEAN\b", "BOOLEAN (should be SMALLINT)"),
    (r"\bWITHOUT\s+ROWID\b", "WITHOUT ROWID"),
    (r"strftime", "strftime()"),
    (r"json_extract", "json_extract()"),
    (r"\bDEFAULT\s+TRUE\b", "DEFAULT TRUE"),
    (r"\bDEFAULT\s+FALSE\b", "DEFAULT FALSE"),
    # IGNORE is converted below; a surviving INSERT OR REPLACE needs a conflict
    # target we can't infer mechanically, so fail and force a manual decision.
    (r"\bINSERT\s+OR\s+(IGNORE|REPLACE)\b", "INSERT OR IGNORE/REPLACE"),
]


def transpile(sql: str) -> str:
    # 1. rowid-alias PK: must run before the generic INTEGER -> BIGINT.
    sql = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGSERIAL PRIMARY KEY", sql)
    # 2. the lone real BOOLEAN -> SMALLINT, and its boolean-literal defaults -> 0/1.
    sql = re.sub(r"\bBOOLEAN\b", "SMALLINT", sql)
    sql = re.sub(r"\bDEFAULT\s+TRUE\b", "DEFAULT 1", sql)
    sql = re.sub(r"\bDEFAULT\s+FALSE\b", "DEFAULT 0", sql)
    # 3. epoch-seconds default.
    sql = re.sub(r"strftime\(\s*'%s'\s*,\s*'now'\s*\)", "EXTRACT(EPOCH FROM now())::bigint", sql)
    # 4. JSON field extraction in DDL (the events expression index).
    sql = re.sub(r"json_extract\(\s*(\w+)\s*,\s*'\$\.(\w+)'\s*\)", r"(\1::jsonb ->> '\2')", sql)
    # 5. all remaining INTEGER column types -> BIGINT.
    sql = re.sub(r"\bINTEGER\b", "BIGINT", sql)
    # 6. seed-row upserts: SQLite's INSERT OR IGNORE -> PG's ON CONFLICT DO NOTHING.
    #    Non-greedy up to the statement-terminating ';' (seed VALUES carry no ';').
    sql = re.sub(
        r"\bINSERT\s+OR\s+IGNORE(\s+INTO\b.*?)\s*;",
        r"INSERT\1\nON CONFLICT DO NOTHING;",
        sql,
        flags=re.DOTALL | re.IGNORECASE,
    )
    return sql


def guard(sql: str, label: str) -> None:
    for pat, name in FORBIDDEN:
        m = re.search(pat, sql)
        if m:
            line = sql[: m.start()].count("\n") + 1
            sys.exit(f"gen_pg_schema: unhandled SQLite construct '{name}' survived in {label} (line {line})")


def process(src: pathlib.Path, dst: pathlib.Path) -> int:
    sql = src.read_text()
    out = transpile(sql)
    guard(out, str(src))
    # Parity: same number of CREATE TABLE statements.
    n_src = len(re.findall(r"CREATE TABLE", sql, re.I))
    n_out = len(re.findall(r"CREATE TABLE", out, re.I))
    if n_src != n_out:
        sys.exit(f"gen_pg_schema: table-count mismatch in {src} ({n_src} -> {n_out})")
    dst.parent.mkdir(parents=True, exist_ok=True)
    # Header records the source as a repo-relative path (machine-independent —
    # an absolute path would bake the build host's directory layout into a
    # committed file and churn on every machine).
    try:
        src_label = src.resolve().relative_to(pathlib.Path.cwd()).as_posix()
    except ValueError:
        src_label = src.as_posix()
    dst.write_text(HEADER.format(src=src_label) + out)
    return n_src


def main() -> None:
    root = pathlib.Path(__file__).resolve().parent.parent
    schema = root / "schema"
    total_tables = 0
    total_files = 0

    # Main consolidated schema.
    total_tables += process(schema / "schema.sql", schema / "postgres" / "schema.sql")
    total_files += 1

    # Webhook schema files (loaded separately at runtime).
    wh_src = schema / "webhooks"
    if wh_src.is_dir():
        for f in sorted(wh_src.glob("*.sql")):
            total_tables += process(f, schema / "postgres" / "webhooks" / f.name)
            total_files += 1

    print(f"✅ Generated Postgres schema: {total_files} file(s), {total_tables} table(s) under schema/postgres/")


if __name__ == "__main__":
    main()
